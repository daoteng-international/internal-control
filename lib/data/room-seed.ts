export function expandSeedRooms() {
  const out: {
    roomNo: string;
    floorId: string;
    featureDesc: string;
    capacityMax: number;
    priceBase: number;
    priceHalfYear: number;
    priceYearly: number;
    areaPing: number;
    status: RoomStatus;
    note: string;
    active: boolean;
  }[] = [];

  SEED_ROOMS.forEach(({ floorCode, rows }) => {
    rows.forEach((r) => {
      const [roomNo, featureDesc, capacityMax, priceBase, priceHalfYear, priceYearly, areaPing, status, note] = r;
      out.push({
        roomNo,
        floorId: floorCode,
        featureDesc,
        capacityMax,
        priceBase,
        priceHalfYear,
        priceYearly,
        areaPing,
        status,
        note,
        // 會議室與不對外出租的空間先停用，避免出現在提案的房號選單
        active: status !== "MAINTENANCE",
      });
    });
  });

  return out;
}
